#!/usr/bin/env python3
"""Write data/languages/ge11.slaspec, the SLEIGH spec of the IMPACT GE11
geometry-engine microcode.

Usage: gen_slaspec.py [OUT]   (default: ../data/languages/ge11.slaspec)

The GE11 runs the same 72-bit instruction set as the InfiniteReality (KONA)
geometry engine: where both chips' assemblers shipped the same word W, they
decoded it to the same 256-bit record (9132 of the 9133 words W the two
production programs share; the odd one, 782001d7c000000000, differs in
record bits 41 and 42, inside the r62 group no semantics reads). So the common spec is not written twice. kona_gen_slaspec.py is a
verbatim copy of the KONA generator (kona repository,
sleigh/kona-ge/tools/gen_slaspec.py at b4a734e) and this script runs it,
then applies the GE11 edits below. Each edit must match the shared text
exactly once, so a refreshed copy that moved a line fails here instead of
silently dropping a GE11 fact. tests/check.py compares the copy with a
sibling kona checkout when one is present.

GE11-only facts (the KONA documents leave each one open for KONA):
  - integer add 0x40 saturates at the signed limit: the 6.5.7 diagnostic's
    iadd test expects 0x7fffffff + 0x7fffffff = 0x7fffffff
    (stand/arcs/ide/isddevices/graphics/MGRAS/mgras_ge11_main.c);
  - the address unit adds 18-bit values and wraps: the aalu3 test expects
    (0x3fffe + 2) = 0 and (0x3ffff + 0x3ffff) = 0x3fffe in the low 18 bits
    (same file). The spec keeps addresses sign-extended from bit 17, which
    keeps 0xfffe0000 (special registers) and 0xffff0000 (output window) as
    the program writes them;
  - special register 6 (CHIP_REV) is read at 0xfffe0018 by the revision
    program the kernel loads (stand/arcs/lib/libsk/graphics/MGRAS/
    mgras_init.c); the importer labels it.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import kona_gen_slaspec as shared  # noqa: E402

OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', 'data', 'languages', 'ge11.slaspec')

HEADER = '''\
# IMPACT GE11 geometry-engine microcode: SLEIGH specification.
# GENERATED by ghidra/processors/ge11/tools/gen_slaspec.py from the shared
# KONA generator (tools/kona_gen_slaspec.py); edit those, not this.
#
# The GE11 and the InfiniteReality (KONA) geometry engine share one 72-bit
# instruction set and one 256-bit decoded record; the labels below
# (ESTABLISHED, INFERRED, UNKNOWN) and the section names they cite (ge_isa.md,
# ge_ops.md) are the KONA repository's documents, ucode/ge_isa.md and
# ucode/ge_ops.md. GE11.h "MICROCODE INSTRUCTION WORD" summarises them.
#
# How the decode works. The chip stores a 72-bit word W. The assembler also
# shipped each word decoded to a 256-bit control record (mgras_ge.u). The
# decode from W is not known as logic, so the loader
# (ghidra_scripts/GE11Import.java) takes the record from a .u file when there
# is one, and otherwise derives it from W with data/ge11_decode.tsv, a table
# learnt from the six GE11 programs that ship both forms. It puts W[63:0] in
# code memory (one 8-byte address unit per word, so code addresses are word
# addresses) and the record groups in the context register at each word.
#
# Semantics modelled (each with its label below): the unit-1 and unit-2
# operations, the seeds, the address unit, stores, the flag word and its
# twelve-word latency, and transfers with their delay slots. Not modelled,
# because no document maps them: r128, r176, r162, r198, r217, r71, r62,
# r25, most of r95 and r110, and the latency of unit results (code that is
# software-pipelined decompiles as if each result were ready at once).
#
# GE11-only (ESTABLISHED by the 6.5.7 diagnostic, see GE11.h): the integer
# add saturates, the address unit wraps at 18 bits, special register 6 is
# CHIP_REV at 0xfffe0018.'''

EDITS = [
    ("# Address registers (A, B, C, G); 18 bits wide on the chip, modelled as 32.",
     "# Address registers (A, B, C, G); 18 bits wide, ESTABLISHED for the GE11 by\n"
     "# the aalu3 test. Held here sign-extended from bit 17 (see AUS)."),
    ("AUS: is CSR & AOP { build CSR; build AOP; }",
     "# GE11: the address unit adds modulo 2^18 (ESTABLISHED, 6.5.7 aalu3 test);\n"
     "# the result is kept sign-extended from bit 17, so the special-register\n"
     "# and output windows keep their 32-bit spellings 0xfffe0000 and 0xffff0000.\n"
     "AUS: is CSR & AOP { build CSR; build AOP; AUV = (AUV << 14) s>> 14; }"),
    ("integer add, ESTABLISHED; saturates at the signed limit, ESTABLISHED for the GE11 (iadd test)",
     "integer add, ESTABLISHED; saturates at the signed limit, GE11-only, ESTABLISHED (6.5.7 iadd test)"),
]


def main():
    out = []
    shared.emit(out)
    # Replace the shared header (everything before the first blank line).
    first_blank = out.index('')
    out = ["%s" % l for l in HEADER.split('\n')] + out[first_blank:]
    text = '\n'.join(out) + '\n'
    for old, new in EDITS:
        n = text.count(old)
        if n != 1:
            sys.exit('gen_slaspec.py: shared text found %d times, expected once: %r' % (n, old))
        text = text.replace(old, new)
    with open(OUT, 'w') as fh:
        fh.write(text)


if __name__ == '__main__':
    main()
